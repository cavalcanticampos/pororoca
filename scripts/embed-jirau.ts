// Embeds the Jirau mod's files into src/jirau-files.ts, so the compiled binary can install it.
// Runs before every build; test/jirau.test.ts fails if the embedded copy is stale.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = join(import.meta.dir, "..", "jirau");
const skip = /(^|\/)(node_modules|\.claude-plugin\/types|tests)(\/|$)/;

export function jirauFiles(): Record<string, string> {
  const out: Record<string, string> = {};
  const walk = (dir: string) => {
    for (const name of readdirSync(dir).sort()) {
      const full = join(dir, name);
      const rel = relative(root, full);
      if (skip.test(rel)) continue;
      if (statSync(full).isDirectory()) walk(full);
      else out[rel] = readFileSync(full, "utf8");
    }
  };
  walk(root);
  return out;
}

export function render(files: Record<string, string>): string {
  return `// Generated by scripts/embed-jirau.ts from jirau/. Do not edit; run \`bun scripts/embed-jirau.ts\`.\nexport const JIRAU_FILES: Record<string, string> = ${JSON.stringify(files, null, 2)};\n`;
}

if (import.meta.main) {
  writeFileSync(join(import.meta.dir, "..", "src", "jirau-files.ts"), render(jirauFiles()));
  console.log("embedded", Object.keys(jirauFiles()).length, "Jirau files");
}
